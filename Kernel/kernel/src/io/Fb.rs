pub fn init(addr: u64, w: u32, h: u32, stride: u32) {
    unsafe {
        FB = (addr + KERNEL_VIRT) as *mut u8;
        FB_W = w as usize;
        FB_H = h as usize;
        FB_STRIDE = stride as usize;
    }
}

pub fn fb_ptr() -> *mut u8 {
    unsafe { FB }
}

pub fn fb_w() -> usize {
    unsafe { FB_W }
}

pub fn fb_h() -> usize {
    unsafe { FB_H }
}

pub fn clear(color: u32) {
    unsafe {
        FB_BG = color;
    }
    unsafe {
        let fb = FB;
        let n = FB_STRIDE * FB_H;
        let mut i = 0;
        while i < n {
            *fb.add(i) = color as u8;
            *fb.add(i + 1) = (color >> 8) as u8;
            *fb.add(i + 2) = (color >> 16) as u8;
            *fb.add(i + 3) = (color >> 24) as u8;
            i += 4;
        }
    }
}

pub fn blit(src: *const u8, w: usize, h: usize, x: usize, y: usize) {
    unsafe {
        let fb = FB;
        for j in 0..h {
            for i in 0..w {
                let dx = x + i;
                let dy = y + j;
                if dx >= FB_W || dy >= FB_H {
                    continue;
                }
                let so = (j * w + i) * 4;
                let off = dy * FB_STRIDE + dx * 4;
                *fb.add(off) = *src.add(so);
                *fb.add(off + 1) = *src.add(so + 1);
                *fb.add(off + 2) = *src.add(so + 2);
                *fb.add(off + 3) = *src.add(so + 3);
            }
        }
    }
}

pub fn draw_char(x: usize, y: usize, ch: u8) {
    if ch < 32 || ch > 127 {
        return;
    }
    let glyph = FONT8X8[(ch - 32) as usize];
    let fg = unsafe { FB_FG };
    let bg = unsafe { FB_BG };
    unsafe {
        let fb = FB;
        for row in 0..FONT_H {
            let bits = glyph[row];
            for col in 0..FONT_W {
                let px_x = x + col;
                let px_y = y + row;
                if px_x >= FB_W || px_y >= FB_H {
                    continue;
                }
                let on = (bits >> (7 - col)) & 1 != 0;
                let c = if on { fg } else { bg };
                let o = px_y * FB_STRIDE + px_x * 4;
                *fb.add(o) = c as u8;
                *fb.add(o + 1) = (c >> 8) as u8;
                *fb.add(o + 2) = (c >> 16) as u8;
                *fb.add(o + 3) = (c >> 24) as u8;
            }
        }
    }
}
